class Edge
{
    final String to;
    final int time;

    Edge(String to, int time)
    {
        this.to = to;
        this.time = time;
    }
}

class Driver
{
    final String id;
    final String location;

    Driver(String id, String location)
    {
        this.id = id;
        this.location = location;
    }
}

class User
{
    final String id;
    final String pickup;

    User(String id, String pickup)
    {
        this.id = id;
        this.pickup = pickup;
    }
}



